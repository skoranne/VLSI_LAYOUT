#!/usr/bin/env julia
# trs_dag.jl — TRS optimizer for CTR files, driven by Lean-verified relations.
#
#   julia trs_dag.jl relations_trs.json input.ctr output.ctr
#
# * Operator semantics follow src/controlparser.f90:
#     `*`/AND2 = intersection, `+`/OR2 = union, NOT/`@`/`!` = difference, XOR/`^` = xor,
#     24 topological selectors (INSIDE, NOT_INSIDE, ..., also "NOT INSIDE").
#   The CTR keyword `AND` is single-layer self-overlap (rhs2 ignored) and, like every other
#   operator, is treated as opaque.
# * Operands are resolved by reaching definition (the definition in effect at that line),
#   so redefinitions of a name are handled correctly.
# * Rules come from the JSON file (generated by trs/gen_relations.py from the Lean-checked
#   lists; each rule names its Lean source).  Every rule rewrites a node to the empty layer,
#   to an existing value (COPY), or to a single selector over existing values, so each
#   application removes work and the rewriting terminates.
# * The Lean relations are cellwise (geometric) equalities.  Selectors read box
#   decompositions, so a COPY / replacement is applied only when the value never reaches a
#   selector operand (`feeds_selector`).  Rewrites to the empty layer are always safe.
# * Empty results are propagated through consumers (X * 0 = 0, X + 0 = X, selector with
#   empty B per the engine's empty-B branch, ...).  A rewritten line is only deleted when
#   no kept line uses its result; otherwise it is kept and annotated.
# * `var trs_enable 0` ... `var trs_enable 1` freezes a region (no rewrites, no removals).
# * A COPY whose source is the lhs name itself is not emitted: `X = X COPY nothing` destroys X
#   in the engine, and the name already holds the value.
# * Inside CONNECT ZONEs nothing is rewritten, and a COPY rewrite is not applied to a value
#   consumed inside a zone (a COPY may carry a different net-id than the original op).

# ---------------------------------------------------------------- minimal JSON reader
function json_parse(s::AbstractString)
    i = Ref(firstindex(s))
    skipws() = while i[] <= lastindex(s) && isspace(s[i[]]); i[] = nextind(s, i[]); end
    function val()
        skipws(); c = s[i[]]
        if c == '{'
            d = Dict{String,Any}(); i[] = nextind(s, i[]); skipws()
            if s[i[]] == '}'; i[] = nextind(s, i[]); return d; end
            while true
                k = val(); skipws(); @assert s[i[]] == ':'; i[] = nextind(s, i[])
                d[k] = val(); skipws()
                if s[i[]] == ','; i[] = nextind(s, i[]); continue; end
                @assert s[i[]] == '}'; i[] = nextind(s, i[]); return d
            end
        elseif c == '['
            a = Any[]; i[] = nextind(s, i[]); skipws()
            if s[i[]] == ']'; i[] = nextind(s, i[]); return a; end
            while true
                push!(a, val()); skipws()
                if s[i[]] == ','; i[] = nextind(s, i[]); continue; end
                @assert s[i[]] == ']'; i[] = nextind(s, i[]); return a
            end
        elseif c == '"'
            io = IOBuffer(); i[] = nextind(s, i[])
            while s[i[]] != '"'
                if s[i[]] == '\\'
                    i[] = nextind(s, i[]); e = s[i[]]
                    write(io, e == 'n' ? '\n' : e == 't' ? '\t' : e)
                else
                    write(io, s[i[]])
                end
                i[] = nextind(s, i[])
            end
            i[] = nextind(s, i[]); return String(take!(io))
        else
            j = i[]
            while i[] <= lastindex(s) && !(s[i[]] in ",]} \n\t\r"); i[] = nextind(s, i[]); end
            t = s[j:prevind(s, i[])]
            return t == "true" ? true : t == "false" ? false : t == "null" ? nothing : parse(Float64, t)
        end
    end
    return val()
end

# ---------------------------------------------------------------- operators
const SEL_BASE = ["INTERACT", "INSIDE", "OUTSIDE", "TOUCH", "CUT", "DISJOINT", "MEET", "EQUAL",
                  "CONTAINS", "COVERS", "COVEREDBY", "OVERLAPS"]
const SELECTORS = Set(vcat(SEL_BASE, ["NOT_" * b for b in SEL_BASE]))
# selectors that keep every A box when B is empty (design_topo_impl.f90, numB == 0 branch)
const KEEP_IF_B_EMPTY = Set(["OUTSIDE", "NOT_INTERACT", "NOT_INSIDE", "NOT_TOUCH", "NOT_CUT",
    "DISJOINT", "NOT_MEET", "NOT_OVERLAPS", "NOT_COVERS", "NOT_COVEREDBY", "NOT_CONTAINS",
    "NOT_EQUAL"])
const SYMOPS = Dict('*' => "*", '+' => "+", '@' => "NOT", '!' => "NOT", '^' => "^")
const WORDOPS = Dict("AND2" => "*", "OR2" => "+", "NOT" => "NOT", "XOR" => "^")

# ---------------------------------------------------------------- patterns
abstract type Pat end
struct PVar <: Pat; name::String; end
struct POp <: Pat; op::String; l::Pat; r::Pat; end

function parse_pat(s::AbstractString)
    toks = String[]
    for m in eachmatch(r"\(|\)|[^\s()]+", s); push!(toks, m.match); end
    pos = Ref(1)
    function p()
        t = toks[pos[]]; pos[] += 1
        if t == "("
            l = p(); op = toks[pos[]]; pos[] += 1; r = p()
            @assert toks[pos[]] == ")" "bad pattern: $s"; pos[] += 1
            return POp(op, l, r)
        end
        return PVar(t)
    end
    pt = p(); @assert pos[] == length(toks) + 1 "trailing tokens in pattern: $s"
    return pt
end

render(p::PVar) = p.name
render(p::POp) = "(" * render(p.l) * " " * p.op * " " * render(p.r) * ")"

struct Rule
    name::String
    lhs::Pat
    rhs::String            # "0", a variable, or a rendered sub-pattern / selector
    source::String
end

function load_rules(path)
    j = json_parse(read(path, String))
    rules = Rule[]
    for r in j["rules"]
        get(r, "apply", true) == false && continue
        push!(rules, Rule(r["name"], parse_pat(r["lhs"]), r["rhs"], get(r, "source", "")))
    end
    return rules
end

# ---------------------------------------------------------------- program / DAG
mutable struct Node
    id::Int
    line::Int
    lhs::String
    op::String             # "*", "+", "NOT", "^", a selector name, or "OPAQUE"
    args::Vector{Int}      # values: >0 node id, <0 leaf id
    zone::Int
    state::Symbol          # :keep, :zero, :alias, :replace
    target::Int            # alias target value
    newop::String          # for :replace
    newargs::Vector{Int}
    why::String
    frozen::Bool           # defined under `var trs_enable 0`: never rewritten or removed
end

mutable struct Prog
    lines::Vector{String}
    nodes::Vector{Node}
    leaves::Vector{String}
    line_node::Dict{Int,Int}
    refs::Dict{Int,Vector{Tuple{Int,Int}}}   # line -> [(value, kind)] references made by that line
    defs_at::Vector{Dict{String,Int}}        # name -> value in effect *before* each line
    memdbs::Set{String}
    zones::Set{Int}
end

dbof(name) = (k = findfirst(':', name); k === nothing ? "" : name[1:k-1])

function parse_ctr(path)
    lines = readlines(path)
    P = Prog(lines, Node[], String[], Dict{Int,Int}(), Dict{Int,Vector{Tuple{Int,Int}}}(),
             Dict{String,Int}[], Set{String}(), Set{Int}())
    cur = Dict{String,Int}()
    leafid = Dict{String,Int}()
    resolve(nm) = haskey(cur, nm) ? cur[nm] :
        (haskey(leafid, nm) ? leafid[nm] : (push!(P.leaves, nm); leafid[nm] = -length(P.leaves)))
    zone = 0
    enabled = true
    for (li, ln) in enumerate(lines)
        push!(P.defs_at, copy(cur))
        s = strip(ln)
        if (m = match(r"(?i)^START\s+CONNECT\s+ZONE\s+(\d+)", s)) !== nothing
            zone = parse(Int, m.captures[1]); push!(P.zones, zone); continue
        elseif occursin(r"(?i)^END\s+CONNECT\s+ZONE", s)
            zone = 0; continue
        elseif (m = match(r"(?i)^decl\s+memory\s+(\S+)\s*=", s)) !== nothing
            push!(P.memdbs, m.captures[1]); continue
        end
        startswith(s, "#") && continue
        if (m = match(r"^var\s+trs_enable\s+(\S+)", s)) !== nothing
            enabled = m.captures[1] != "0"
        end
        m = match(r"(?i)^exec\s+run\s+(\S+)\s*=\s*(\S+)\s*(.*)$", s)
        if m === nothing
            # any other line: references to layer names count as uses of their reaching defs
            r = Tuple{Int,Int}[]
            for t in eachmatch(r"[A-Za-z_0-9]+:[A-Za-z_0-9.]+", s)
                haskey(cur, t.match) && push!(r, (cur[t.match], 0))
            end
            P.refs[li] = r
            continue
        end
        lhs, a, rest = String(m.captures[1]), String(m.captures[2]), String(m.captures[3])
        k = findfirst(c -> c in "+@*%^~!", rest)
        op = "OPAQUE"; b = ""
        if k !== nothing                       # engine scans for single-char ops first
            c = rest[k]
            op = get(SYMOPS, c, "OPAQUE")
            tk = split(strip(rest[nextind(rest, k):end]))
            b = isempty(tk) ? "" : String(tk[1])
        else
            tk = split(rest)
            if length(tk) >= 2
                w1 = uppercase(tk[1])
                # edge operators (INSIDE EDGE, NOT COINCIDENT OUTSIDE EDGE, ...) are opaque; this
                # must be tested first, else "NOT INSIDE EDGE x" would parse as difference.
                if any(t -> uppercase(t) in ("EDGE", "COINCIDENT"), tk[1:min(end, 4)])
                    op = "OPAQUE"; b = String(tk[end])
                elseif w1 == "NOT" && length(tk) >= 3 && uppercase(tk[2]) in SEL_BASE
                    op = "NOT_" * uppercase(tk[2]); b = String(tk[3])
                elseif haskey(WORDOPS, w1)
                    op = WORDOPS[w1]; b = String(tk[2])
                elseif w1 in SELECTORS
                    op = w1; b = String(tk[2])
                else
                    op = "OPAQUE"; b = String(tk[2])
                end
            end
        end
        args = Int[resolve(a)]
        !isempty(b) && b != "nothing" && push!(args, resolve(b))
        if op != "OPAQUE" && length(args) != 2; op = "OPAQUE"; end
        nd = Node(length(P.nodes) + 1, li, lhs, op, args, zone, :keep, 0, "", Int[], "", !enabled)
        push!(P.nodes, nd)
        P.line_node[li] = nd.id
        P.refs[li] = [(v, 1) for v in args]
        cur[lhs] = nd.id
    end
    push!(P.defs_at, copy(cur))
    return P
end

# ---------------------------------------------------------------- rewriting
function resolvev(P, v)
    while v > 0 && P.nodes[v].state == :alias; v = P.nodes[v].target; end
    return v
end
iszero(P, v) = v > 0 && P.nodes[v].state == :zero

function pmatch(P, p::PVar, v, env)
    v = resolvev(P, v)
    haskey(env, p.name) && return env[p.name] == v
    env[p.name] = v; return true
end
function pmatch(P, p::POp, v, env)
    v = resolvev(P, v)
    v > 0 || return false
    n = P.nodes[v]
    (n.state == :keep && n.zone == 0 && n.op == p.op) || return false
    pmatch(P, p.l, n.args[1], env) && pmatch(P, p.r, n.args[2], env) || return false
    env[render(p)] = v
    return true
end

"Can value `v` be referred to by its name at line `li`? (no intervening redefinition)"
function nameable(P, v, li)
    v < 0 && return !haskey(P.defs_at[li], P.leaves[-v]) || P.defs_at[li][P.leaves[-v]] == v
    nm = P.nodes[v].lhs
    return get(P.defs_at[li], nm, 0) == v
end
vname(P, v) = v < 0 ? P.leaves[-v] : P.nodes[v].lhs

function consumed_in_zone(P, id)
    for n in P.nodes
        n.zone > 0 && any(a -> resolvev(P, a) == id || a == id, n.args) && return true
    end
    return false
end

"""
Does value `id` reach a selector operand through any chain of later ops?  Selectors read box
decompositions, not just geometry, so a cellwise-equal replacement (COPY or a different op)
is only safe when the answer is no.  (Empty results have no boxes and are always safe.)
"""
function feeds_selector(P, id)
    seen = Set{Int}(); stack = [id]
    while !isempty(stack)
        v = pop!(stack)
        v in seen && continue
        push!(seen, v)
        for m in P.nodes
            (v in m.args || (m.state == :alias && m.target == v)) || continue
            m.op in SELECTORS && return true
            push!(stack, m.id)
        end
    end
    return false
end

function set_alias!(P, n, t, why; box_equal = false)
    (nameable(P, t, n.line) && !consumed_in_zone(P, n.id)) || return false
    (box_equal || !feeds_selector(P, n.id)) || return false
    n.state = :alias; n.target = t; n.why = why; return true
end

function fold!(P, n)
    a = resolvev(P, n.args[1]); b = resolvev(P, n.args[2])
    za, zb = iszero(P, a), iszero(P, b)
    (za || zb) || return false
    op = n.op
    if op == "*"
        n.state = :zero; n.why = "X * 0 = 0"; return true
    elseif op == "+" || op == "^"
        return za ? set_alias!(P, n, b, "0 $op X = X") : set_alias!(P, n, a, "X $op 0 = X")
    elseif op == "NOT"
        za && (n.state = :zero; n.why = "0 NOT X = 0"; return true)
        return set_alias!(P, n, a, "X NOT 0 = X")
    elseif op in SELECTORS
        za && (n.state = :zero; n.why = "selector on empty A = 0"; return true)
        if op in KEEP_IF_B_EMPTY
            return set_alias!(P, n, a, "A $op 0 = A (engine empty-B branch)")
        end
        n.state = :zero; n.why = "A $op 0 = 0 (engine empty-B branch)"; return true
    end
    return false
end

function apply_rule!(P, n, r::Rule)
    env = Dict{String,Int}()
    pmatch(P, r.lhs, n.id, env) || return false
    why = "$(r.name) [$(r.source)]"
    if r.rhs == "0"
        n.state = :zero; n.why = why; return true
    elseif haskey(env, r.rhs)
        return set_alias!(P, n, env[r.rhs], why)
    else
        q = parse_pat(r.rhs)
        if q isa POp && q.op in SELECTORS && q.l isa PVar && q.r isa PVar &&
           haskey(env, q.l.name) && haskey(env, q.r.name)
            x, y = env[q.l.name], env[q.r.name]
            (nameable(P, x, n.line) && nameable(P, y, n.line) && !consumed_in_zone(P, n.id) &&
             vname(P, x) != n.lhs && vname(P, y) != n.lhs &&    # no in-place op (engine aliasing)
             !feeds_selector(P, n.id)) || return false
            n.state = :replace; n.newop = q.op; n.newargs = [x, y]; n.why = why; return true
        end
    end
    return false
end

"Built-in: σ(σ(A,B),B) = σ(A,B) (Lean: Trs.Box.sel_idem)."
function sel_idem!(P, n)
    n.op in SELECTORS || return false
    a = resolvev(P, n.args[1]); b = resolvev(P, n.args[2])
    a > 0 || return false
    m = P.nodes[a]
    (m.state == :keep && m.op == n.op && resolvev(P, m.args[2]) == b) || return false
    # nest_eq is a box-list equality, so this COPY is safe even under later selectors
    return set_alias!(P, n, a, "sel_idem [Trs.Box.nest_eq]"; box_equal = true)
end

function optimize!(P, rules)
    # TRS_MAX_REWRITES (debugging aid): stop after that many rewrites
    limit = parse(Int, get(ENV, "TRS_MAX_REWRITES", string(typemax(Int))))
    count = 0
    for n in P.nodes
        count >= limit && break
        (n.zone > 0 || n.frozen || n.op == "OPAQUE") && continue
        if fold!(P, n) || sel_idem!(P, n) || any(r -> apply_rule!(P, n, r), rules)
            count += 1
            count == limit && @info "last rewrite" n.line n.lhs n.why
        end
    end
end

# ---------------------------------------------------------------- emission
function live_lines(P)
    # A provably-empty line, or a memory temporary orphaned by TRS, is dropped when no kept
    # line references its value.  Iterate to a fixpoint.
    orig_used = Set{Int}()
    for (_, r) in P.refs, (v, _) in r; v > 0 && push!(orig_used, v); end
    dropped = Set{Int}()
    while true
        used = Set{Int}()
        for (li, r) in P.refs
            haskey(P.line_node, li) && P.line_node[li] in dropped && continue
            nid = get(P.line_node, li, 0)
            if nid > 0
                n = P.nodes[nid]
                # a kept empty line is emitted verbatim, so its operands stay live
                if n.state == :alias
                    push!(used, n.target); continue
                elseif n.state == :replace
                    foreach(v -> push!(used, v), n.newargs); continue
                end
            end
            for (v, _) in r; push!(used, v); end
        end
        changed = false
        for n in P.nodes
            n.id in dropped && continue
            (n.id in used || n.frozen) && continue
            dbof(n.lhs) in P.memdbs || continue
            # delete provably-empty results, and temporaries that only fed rewritten ops;
            # COPY / single-op replacements are always emitted (they keep the name defined)
            if n.state == :zero || (n.state == :keep && n.id in orig_used && n.op != "OPAQUE")
                push!(dropped, n.id); changed = true
            end
        end
        changed || return dropped
    end
end

function write_ctr(path, P)
    dropped = live_lines(P)
    out = String[]
    stats = Dict(:removed => 0, :copy => 0, :replace => 0, :kept_empty => 0, :orphan => 0)
    for (li, ln) in enumerate(P.lines)
        nid = get(P.line_node, li, 0)
        if nid == 0
            push!(out, ln); continue
        end
        n = P.nodes[nid]
        if n.id in dropped
            if n.state == :keep
                push!(out, "# TRS: removed (result no longer used): $(strip(ln))"); stats[:orphan] += 1
            else
                push!(out, "# TRS: removed, $(n.state == :zero ? "provably empty" : "redundant") by $(n.why)")
                push!(out, "# $(strip(ln))"); stats[:removed] += 1
            end
        elseif n.state == :zero
            push!(out, "# TRS: provably empty by $(n.why); kept because $(n.lhs) is used later")
            push!(out, ln); stats[:kept_empty] += 1
        elseif n.state == :alias && vname(P, n.target) == n.lhs
            # the name already holds the value; the engine's `X = X COPY nothing` destroys X
            push!(out, "# TRS: removed, $(n.lhs) already holds this value by $(n.why)")
            push!(out, "# $(strip(ln))"); stats[:removed] += 1
        elseif n.state == :alias
            push!(out, "# TRS: $(n.why)")
            push!(out, "exec run $(n.lhs) = $(vname(P, n.target)) COPY nothing"); stats[:copy] += 1
        elseif n.state == :replace
            push!(out, "# TRS: $(n.why)")
            push!(out, "exec run $(n.lhs) = $(vname(P, n.newargs[1])) $(n.newop) $(vname(P, n.newargs[2]))")
            stats[:replace] += 1
        else
            push!(out, ln)
        end
    end
    open(path, "w") do io; foreach(l -> println(io, l), out); end
    return stats
end

function main()
    if length(ARGS) < 3
        println("Usage: julia trs_dag.jl relations_trs.json input.ctr output.ctr"); exit(1)
    end
    rules = load_rules(ARGS[1])
    P = parse_ctr(ARGS[2])
    optimize!(P, rules)
    st = write_ctr(ARGS[3], P)
    nops = length(P.nodes)
    removed = st[:removed] + st[:orphan]
    println("Rules loaded:            $(length(rules))")
    println("Ops before:              $nops")
    println("Ops removed:             $removed  (rewritten $(st[:removed]), orphaned $(st[:orphan]))")
    println("Ops replaced by COPY:    $(st[:copy])")
    println("Ops replaced by 1 op:    $(st[:replace])")
    println("Provably empty, kept:    $(st[:kept_empty])")
    println("Ops after:               $(nops - removed)")
    println("Connectivity zones:      $(length(P.zones)) (no rewrites inside)")
end

main()
