#!/usr/bin/env julia
# Julia generator: Super-Resolution + Image Processing hardware datapath (>= 1M gates)
# Scaled, optimization-resistant: each PE has unique coefficients/registered state contributing to output.

function coeff(i, f, taps)
    v = ((i*1103515245 + f*12345 + 1013904223) % taps) - (taps ÷ 2)
    v == 0 ? 1 : v
end

function gen_sr_1m(; name="SRImageProc1M", W=8, CHANNELS=1, IMGW=32, PE_ROWS=256, PE_COLS=256, FILTERS=4)
    total_pes = PE_ROWS * PE_COLS * FILTERS
    pes_per_filter = PE_ROWS * PE_COLS
    io = IOBuffer()
    LB = IMGW
    AW = max(1, ceil(Int, log2(LB)))
    ACCW = 2*W + 16
    println(io, "// Generated by Julia SR+ImageProc datapath generator (>=1M gate target)")
    println(io, "// name=$name W=$W CH=$CHANNELS IMGW=$IMGW PE_ROWS=$PE_ROWS PE_COLS=$PE_COLS FILTERS=$FILTERS TOTAL_PES=$total_pes")
    println(io, "module $name(")
    println(io, "  input clk, input rst_n,")
    println(io, "  input in_valid,")
    println(io, "  input [$(W*CHANNELS-1):0] pixel_in,")
    println(io, "  output reg [$(W*CHANNELS-1):0] pixel_out,")
    println(io, "  output reg out_valid")
    println(io, ");")
    for ch in 0:CHANNELS-1
        println(io, "  (* ram_style = \"register\" *) reg signed [$(W-1):0] lb0_c$(ch) [0:$(LB-1)];")
        println(io, "  (* ram_style = \"register\" *) reg signed [$(W-1):0] lb1_c$(ch) [0:$(LB-1)];")
    end
    println(io, "  reg [$(AW)-1:0] wptr;")
    # PEs: unique comb mul + registered product (keep) so optimization can't merge
    for f in 0:FILTERS-1
        for i in 0:pes_per_filter-1
            gid = f*pes_per_filter + i
            addr = (i*31 + f*17 + gid*7) % LB
            ch = (i + f) % CHANNELS
            lb = ((i + f) % 2 == 0) ? "lb0" : "lb1"
            cval = coeff(gid, f, 31)
            ac = abs(cval)
            mul_expr = cval >= 0 ? "\$signed($(W+1)'sd$cval)" : "-\$signed($(W+1)'sd$ac)"
            println(io, "  wire signed [$(2*W):0] pe_mul_$gid = \$signed($(lb)_c$(ch)[$addr]) * $mul_expr;")
            println(io, "  (* keep = \"true\" *) reg signed [$(2*W):0] pe_r_$gid;")
        end
    end
    # reduction per filter: sum registered PE outputs in groups
    gsz = 16
    ng = cld(pes_per_filter, gsz)
    for f in 0:FILTERS-1
        base = f*pes_per_filter
        for g in 0:ng-1
            s = g*gsz
            e = min((g+1)*gsz-1, pes_per_filter-1)
            terms = join(["\$signed(pe_r_$(base+j))" for j in s:e], " + ")
            println(io, "  wire signed [$(ACCW):0] f$(f)_g$(g) = $terms;")
        end
        gterms = join(["f$(f)_g$(g)" for g in 0:ng-1], " + ")
        println(io, "  (* keep = \"true\" *) reg signed [$(ACCW):0] f$(f)_acc;")
        println(io, "  wire signed [$(ACCW):0] f$(f)_sum = $gterms;")
    end
    println(io, "  (* keep = \"true\" *) reg signed [$(ACCW):0] out_acc;")
    println(io, "  always @(posedge clk or negedge rst_n) begin")
    println(io, "    if(!rst_n) begin")
    println(io, "      wptr <= 0; out_valid <= 0; pixel_out <= 0; out_acc <= 0;")
    for f in 0:FILTERS-1
        println(io, "      f$(f)_acc <= 0;")
    end
    # init PE regs in reset (Yosys handles; keep compact)
    println(io, "    end else begin")
    println(io, "      out_valid <= in_valid;")
    println(io, "      if(in_valid) begin")
    for ch in 0:CHANNELS-1
        println(io, "        lb1_c$(ch)[wptr] <= lb0_c$(ch)[wptr];")
        println(io, "        lb0_c$(ch)[wptr] <= \$signed(pixel_in[$((ch+1)*W-1):$(ch*W)]);")
    end
    println(io, "        wptr <= wptr + 1'b1;")
    # register all PE muls
    for gid in 0:total_pes-1
        println(io, "        pe_r_$gid <= pe_mul_$gid;")
    end
    for f in 0:FILTERS-1
        println(io, "        f$(f)_acc <= f$(f)_sum;")
    end
    println(io, "        out_acc <= f0_acc + f1_acc - f2_acc + (f$(FILTERS-1)_acc >>> 1);")
    println(io, "        pixel_out <= out_acc[$(W-1):0];")
    println(io, "      end else begin")
    # hold/registers still update to keep logic? not necessary
    for gid in 0:total_pes-1
        println(io, "        pe_r_$gid <= pe_mul_$gid;")
    end
    println(io, "      end")
    println(io, "    end")
    println(io, "  end")
    println(io, "endmodule")
    return (verilog=String(take!(io)), total_pes=total_pes)
end

if abspath(PROGRAM_FILE) == @__FILE__
    function main()
        cfg = (W=8, CHANNELS=1, IMGW=32, PE_ROWS=128, PE_COLS=128, FILTERS=4) # 65536 PEs -> ~131k regs+logic
        name = "SRImageProc1M"
        out = joinpath(@__DIR__, "sr_imageproc_1m.v")
        i = 1
        while i <= length(ARGS)
            a = ARGS[i]
            if a == "--1m" || a == "1m"
                cfg = (W=8, CHANNELS=1, IMGW=32, PE_ROWS=256, PE_COLS=256, FILTERS=4) # 262144 PEs
            elseif a == "--big"
                cfg = (W=8, CHANNELS=1, IMGW=32, PE_ROWS=160, PE_COLS=160, FILTERS=4) # 102400 PEs
            elseif a == "--test"
                cfg = (W=8, CHANNELS=1, IMGW=16, PE_ROWS=32, PE_COLS=32, FILTERS=3) # 3072 PEs
            elseif a == "-o" && i < length(ARGS)
                i += 1; out = ARGS[i]
            elseif a == "--name" && i < length(ARGS)
                i += 1; name = ARGS[i]
            end
            i += 1
        end
        res = gen_sr_1m(; name=name, cfg...)
        open(out,"w") do f; write(f,res.verilog); end
        println("wrote $out total_pes=$(res.total_pes) bytes=$(length(res.verilog))")
    end
    main()
end
