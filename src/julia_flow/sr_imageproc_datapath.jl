#!/usr/bin/env julia
# Julia generator: Super-Resolution + Image Processing hardware datapath
# Architecture:
#  - Streaming input with line buffers
#  - 2x bilinear upsample-style multi-tap sampling datapath
#  - Parallel convolution filter banks (blur, sharpen, edge/sobel)
#  - Large replicated MAC processing-element arrays and reduction trees
#  - Parameterized to scale to >= 1,000,000 gates (Yosys mapped cells)
#
# Emits synthesizable Verilog. Gate count scales with PE_ROWS*PE_COLS*FILTERS.

function coeff(i, f, taps)
    v = ((i*13 + f*37 + 5) % taps) - (taps ÷ 2)
    v == 0 ? 1 : v
end

function gen_sr_datapath(; name="SRImageProc1M", W=8, CHANNELS=1, IMGW=32, PE_ROWS=64, PE_COLS=64, FILTERS=3)
    total_pes = PE_ROWS * PE_COLS * FILTERS
    io = IOBuffer()
    LB = IMGW
    AW = max(1, ceil(Int, log2(LB)))
    ACCW = 2*W + 20
    pes_per_filter = PE_ROWS * PE_COLS
    println(io, "// Generated by Julia SR+ImageProc datapath generator")
    println(io, "// Super-resolution + image processing (convolution filter banks, upsample datapath)")
    println(io, "// name=$name W=$W CH=$CHANNELS IMGW=$IMGW PE_ROWS=$PE_ROWS PE_COLS=$PE_COLS FILTERS=$FILTERS TOTAL_PES=$total_pes")
    println(io, "module $name(")
    println(io, "  input clk, input rst_n,")
    println(io, "  input in_valid,")
    println(io, "  input [$(W*CHANNELS-1):0] pixel_in,")
    println(io, "  output reg [$(W*CHANNELS-1):0] pixel_out,")
    println(io, "  output reg out_valid")
    println(io, ");")
    # line buffers per channel
    for ch in 0:CHANNELS-1
        println(io, "  reg signed [$(W-1):0] lb0_c$(ch) [0:$(LB-1)];")
        println(io, "  reg signed [$(W-1):0] lb1_c$(ch) [0:$(LB-1)];")
        println(io, "  reg signed [$(W-1):0] lb2_c$(ch) [0:$(LB-1)];")
    end
    println(io, "  reg [$(AW)-1:0] wptr;")
    # PE multipliers (combinational) - all used in reductions
    for f in 0:FILTERS-1
        for i in 0:pes_per_filter-1
            gid = f*pes_per_filter + i
            addr = (i * 7 + f*13 + 3) % LB
            ch = (i + f) % CHANNELS
            cval = coeff(i, f, 17)
            ac = abs(cval)
            println(io, "  wire signed [$(2*W):0] pe_mul_$gid = \$signed(lb$(i % 3)_c$(ch)[$addr]) * " * (cval >= 0 ? "\$signed($(W+1)'sd$cval)" : "-\$signed($(W+1)'sd$ac)") * ";")
        end
    end
    # Reduction trees: partial group sums per filter (wires) -> filter acc regs
    gsz = 32
    ng = cld(pes_per_filter, gsz)
    for f in 0:FILTERS-1
        base = f*pes_per_filter
        for g in 0:ng-1
            s = g*gsz
            e = min((g+1)*gsz-1, pes_per_filter-1)
            terms = join(["\$signed({{$(ACCW-2*W-1){pe_mul_$(base+j)[$(2*W)]}}, pe_mul_$(base+j)})" for j in s:e], " + ")
            println(io, "  wire signed [$(ACCW):0] f$(f)_g$(g) = $terms;")
        end
        # combine group sums
        gterms = join(["f$(f)_g$(g)" for g in 0:ng-1], " + ")
        println(io, "  wire signed [$(ACCW):0] f$(f)_sum = $gterms;")
        println(io, "  reg signed [$(ACCW):0] f$(f)_acc;")
    end
    # Super-res/upsample combine: interp from filter outputs
    println(io, "  wire signed [$(ACCW):0] up_interp = f0_sum + (f1_sum >>> 1);")
    println(io, "  wire signed [$(ACCW):0] edge_enh = up_interp + f2_sum - (f0_sum >>> 2);")
    println(io, "  reg signed [$(ACCW):0] out_acc;")
    println(io, "  always @(posedge clk or negedge rst_n) begin")
    println(io, "    if(!rst_n) begin")
    println(io, "      wptr <= 0; out_valid <= 0; pixel_out <= 0; out_acc <= 0;")
    for f in 0:FILTERS-1
        println(io, "      f$(f)_acc <= 0;")
    end
    for ch in 0:CHANNELS-1
        for k in 0:LB-1
            # avoid huge init loops in Verilog; reset not strictly needed for synth arrays but be reasonable
        end
    end
    println(io, "    end else begin")
    println(io, "      out_valid <= in_valid;")
    println(io, "      if(in_valid) begin")
    for ch in 0:CHANNELS-1
        println(io, "        lb2_c$(ch)[wptr] <= lb1_c$(ch)[wptr];")
        println(io, "        lb1_c$(ch)[wptr] <= lb0_c$(ch)[wptr];")
        println(io, "        lb0_c$(ch)[wptr] <= \$signed(pixel_in[$((ch+1)*W-1):$(ch*W)]);")
    end
    println(io, "        wptr <= wptr + 1'b1;")
    for f in 0:FILTERS-1
        println(io, "        f$(f)_acc <= f$(f)_sum;")
    end
    println(io, "        out_acc <= edge_enh;")
    println(io, "        pixel_out <= out_acc[$(W-1):0];")
    println(io, "      end")
    println(io, "    end")
    println(io, "  end")
    println(io, "endmodule")
    return (verilog=String(take!(io)), total_pes=total_pes)
end

if abspath(PROGRAM_FILE) == @__FILE__
    function main()
        cfg = (W=8, CHANNELS=1, IMGW=32, PE_ROWS=32, PE_COLS=32, FILTERS=3)
        name = "SRImageProc1M"
        out = joinpath(@__DIR__, "sr_imageproc_1m.v")
        i = 1
        while i <= length(ARGS)
            a = ARGS[i]
            if a == "--1m" || a == "1m"
                cfg = (W=8, CHANNELS=1, IMGW=64, PE_ROWS=192, PE_COLS=192, FILTERS=4) # 147456 PEs
                name = "SRImageProc1M"
            elseif a == "--big"
                cfg = (W=8, CHANNELS=1, IMGW=32, PE_ROWS=128, PE_COLS=128, FILTERS=4) # 65536 PEs
            elseif a == "--test"
                cfg = (W=8, CHANNELS=1, IMGW=16, PE_ROWS=16, PE_COLS=16, FILTERS=3) # 768 PEs
            elseif a == "-o" && i < length(ARGS)
                i += 1; out = ARGS[i]
            elseif a == "--name" && i < length(ARGS)
                i += 1; name = ARGS[i]
            end
            i += 1
        end
        res = gen_sr_datapath(; name=name, cfg...)
        open(out,"w") do f; write(f,res.verilog); end
        println("wrote $out total_pes=$(res.total_pes) bytes=$(length(res.verilog))")
    end
    main()
end
