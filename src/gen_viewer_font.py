#!/usr/bin/env python3
"""Generate viewer_font.f90: the X11 misc-fixed 8x13 bitmap font (public domain) as a Fortran
parameter table for MAGVIEWER text (glBitmap). Rows are stored bottom-to-top, one byte per row,
most significant bit = leftmost pixel, for ASCII 32..126.
   python3 gen_viewer_font.py [/usr/share/fonts/X11/misc/8x13-ISO8859-1.pcf.gz] > viewer_font.f90
"""
import gzip, sys
from PIL import PcfFontFile

path = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/X11/misc/8x13-ISO8859-1.pcf.gz'
f = PcfFontFile.PcfFontFile(gzip.open(path))
W, H, ASC = 8, 13, 11            # cell 8x13, baseline 2 px above the bottom row
rows = {}
for c in range(32, 127):
    g = f.glyph[c]
    cell = [0] * H              # top-to-bottom
    if g is not None and g[3] is not None:
        (dx, dy), (x0, y0, x1, y1), _, im = g
        im = im.convert('1')
        gw, gh = im.size
        for yy in range(gh):
            for xx in range(gw):
                if im.getpixel((xx, yy)):
                    col = x0 + xx
                    row = ASC + y0 + yy          # y0 is negative top offset from baseline
                    if 0 <= col < W and 0 <= row < H:
                        cell[row] |= 0x80 >> col
    rows[c] = list(reversed(cell))  # bottom-to-top for glBitmap
out = ['! Generated by gen_viewer_font.py from the X11 misc-fixed 8x13 font (public domain).',
       '! Do not edit. FONT_BITS(r, c): row r (1 = bottom) of ASCII character c, MSB = left pixel.',
       'module ViewerFontModule',
       '  use, intrinsic :: iso_c_binding, only: c_int8_t',
       '  implicit none',
       '  private',
       '  integer, parameter, public :: FONT_W = %d, FONT_H = %d' % (W, H),
       '  integer(c_int8_t), parameter, public :: FONT_BITS(%d, 32:126) = reshape([ &' % H]
vals = []
for c in range(32, 127):
    vals += [str(v - 256 if v > 127 else v) + '_c_int8_t' for v in rows[c]]
lines = []
for i in range(0, len(vals), 8):
    lines.append('       ' + ', '.join(vals[i:i+8]))
out.append(', &\n'.join(lines) + ' &')
out.append('       ], [%d, 95])' % H)
out.append('end module ViewerFontModule')
print('\n'.join(out))
