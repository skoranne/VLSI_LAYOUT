!> \file trs_optimizer.f90
!> \brief Term-rewrite (TRS) DAG optimizer for CTR programs, driven by Lean-verified rules.
!>
!> Fortran port of trs_dag.jl.  MAGPARSER calls TRSOptimizeFile() on the m4-expanded control
!> file *before* executing it (CTR "compile time"), reading the rewrite rules from a text file
!> (relations_trs.rules, generated by trs/gen_relations.py from the Lean-checked lists).
!>
!>   Enable:  var trs_rules /path/to/relations_trs.rules      (in the CTR)
!>       or:  export MAGPARSER_TRS_RULES=/path/to/relations_trs.rules
!>   Disable for one CTR even if the env var is set:  var trs_rules none
!>   Freeze a region (no rewrites, no removals):      var trs_enable 0 ... var trs_enable 1
!>
!> Semantics (identical to trs_dag.jl, see RELATIONS_TRS.tex):
!>  * `*`/AND2 intersection, `+`/OR2 union, NOT/@/! difference, XOR/^ xor, 24 selectors.
!>    The keyword AND (single-layer self-overlap) and every other operator are opaque.
!>  * Operands are resolved by reaching definition, so redefinitions are handled.
!>  * Every rule rewrites a node to the empty layer, an existing value (COPY), or a single
!>    selector over existing values; each application removes work, so rewriting terminates.
!>  * Lean relations are cellwise equalities; selectors read box decompositions, so a COPY or
!>    replacement is applied only when the value never reaches a selector operand.
!>  * Empty results are propagated (X*0=0, X+0=X, selector empty-B branch of the engine).
!>  * Nothing inside CONNECT ZONEs is rewritten; no COPY of a value consumed inside a zone.
module TRSOptimizerModule
  implicit none
  private
  public :: TRSOptimizeFile, TRSFindRulesFile

  integer, parameter :: LN = 1024     ! max CTR line length
  integer, parameter :: NL = 256      ! max layer-name length
  integer, parameter :: PL = 96       ! max rendered (sub)pattern length
  integer, parameter :: WL = 512      ! max annotation length

  integer, parameter :: ST_KEEP = 0, ST_ZERO = 1, ST_ALIAS = 2, ST_REPLACE = 3
  integer, parameter :: NSEL = 24
  character(len=12), parameter :: SEL_BASE(12) = [character(len=12) :: 'INTERACT', 'INSIDE', &
       'OUTSIDE', 'TOUCH', 'CUT', 'DISJOINT', 'MEET', 'EQUAL', 'CONTAINS', 'COVERS', &
       'COVEREDBY', 'OVERLAPS']
  !> selectors that keep every A box when B is empty (design_topo_impl.f90, numB == 0 branch)
  character(len=16), parameter :: KEEP_IF_B_EMPTY(12) = [character(len=16) :: 'OUTSIDE', &
       'NOT_INTERACT', 'NOT_INSIDE', 'NOT_TOUCH', 'NOT_CUT', 'DISJOINT', 'NOT_MEET', &
       'NOT_OVERLAPS', 'NOT_COVERS', 'NOT_COVEREDBY', 'NOT_CONTAINS', 'NOT_EQUAL']

  ! ------------------------------------------------------------------ string hash map
  type :: strmap
     integer :: cap = 0
     character(len=NL), allocatable :: key(:)
     integer, allocatable :: val(:)
     logical, allocatable :: used(:)
  end type strmap

  ! ------------------------------------------------------------------ patterns and rules
  type :: pattern_pool
     integer :: n = 0
     logical, allocatable :: isop(:)
     character(len=16), allocatable :: name(:)      ! variable name or operator
     integer, allocatable :: l(:), r(:)
     character(len=PL), allocatable :: rend(:)       ! rendered form, used as env key
  end type pattern_pool

  type :: rule_t
     character(len=64)  :: name = ''
     integer            :: lhs = 0
     character(len=PL)  :: rhs = ''
     integer            :: rhs_kind = 0    ! 0 empty, 1 env key, 2 selector over two vars
     character(len=16)  :: rop = '', rl = '', rr = ''
     character(len=128) :: source = ''
  end type rule_t

  ! ------------------------------------------------------------------ program DAG
  type :: node_t
     integer :: line = 0
     character(len=NL) :: lhs = ''
     character(len=16) :: op = 'OPAQUE'
     integer :: nargs = 0
     integer :: args(2) = 0         ! >0 node id, <0 leaf id
     integer :: zone = 0
     integer :: state = ST_KEEP
     integer :: target = 0
     character(len=16) :: newop = ''
     integer :: newargs(2) = 0
     character(len=WL) :: why = ''
     integer :: next_redef = huge(1) ! line of the next node defining the same name
     logical :: frozen = .false.     ! defined while `var trs_enable 0`: never rewritten/removed
  end type node_t

  type :: prog_t
     integer :: nlines = 0
     character(len=LN), allocatable :: lines(:)
     integer :: nnodes = 0
     type(node_t), allocatable :: nodes(:)
     integer :: nleaves = 0
     character(len=NL), allocatable :: leaves(:)
     integer, allocatable :: leaf_first_def(:)
     integer, allocatable :: line_node(:)
     logical, allocatable :: has_refs(:)
     integer, allocatable :: ref_off(:), ref_cnt(:)
     integer :: nref = 0
     integer, allocatable :: refv(:)
     type(strmap) :: memdbs
     integer :: nzones = 0
     ! users graph for feeds_selector (static args + dynamic alias edges)
     integer, allocatable :: ehead(:), enext(:), eto(:)
     integer :: nedge = 0
  end type prog_t

contains

  ! ================================================================== small string helpers
  pure function upper(s) result(r)
    character(len=*), intent(in) :: s
    character(len=len(s)) :: r
    integer :: i
    r = s
    do i = 1, len(s)
       if (r(i:i) >= 'a' .and. r(i:i) <= 'z') r(i:i) = achar(iachar(r(i:i)) - 32)
    end do
  end function upper

  pure logical function is_space(c)
    character, intent(in) :: c
    is_space = (c == ' ' .or. c == achar(9) .or. c == achar(13) .or. c == achar(10))
  end function is_space

  pure logical function is_idc(c)
    character, intent(in) :: c
    is_idc = (c >= 'A' .and. c <= 'Z') .or. (c >= 'a' .and. c <= 'z') .or. &
             (c >= '0' .and. c <= '9') .or. c == '_'
  end function is_idc

  !> split s into whitespace-separated tokens
  subroutine split_ws(s, tok, nt)
    character(len=*), intent(in) :: s
    character(len=NL), intent(out) :: tok(:)
    integer, intent(out) :: nt
    integer :: i, j, n
    n = len_trim(s); nt = 0; i = 1
    do while (i <= n)
       if (is_space(s(i:i))) then
          i = i + 1; cycle
       end if
       j = i
       do while (j <= n)
          if (is_space(s(j:j))) exit
          j = j + 1
       end do
       if (nt < size(tok)) then
          nt = nt + 1; tok(nt) = s(i:j-1)
       end if
       i = j
    end do
  end subroutine split_ws

  pure function itoa(i) result(s)
    integer, intent(in) :: i
    character(len=:), allocatable :: s
    character(len=24) :: b
    write(b, '(I0)') i
    s = trim(b)
  end function itoa

  logical function is_selector(op)
    character(len=*), intent(in) :: op
    integer :: k
    character(len=16) :: o
    o = op
    is_selector = .false.
    do k = 1, 12
       if (o == SEL_BASE(k) .or. o == 'NOT_' // SEL_BASE(k)) then
          is_selector = .true.; return
       end if
    end do
  end function is_selector

  logical function in_sel_base(w)
    character(len=*), intent(in) :: w
    in_sel_base = any(SEL_BASE == w)
  end function in_sel_base

  ! ================================================================== hash map
  subroutine sm_init(m, n)
    type(strmap), intent(inout) :: m
    integer, intent(in) :: n
    integer :: c
    c = 64
    do while (c < 2*n + 16); c = 2*c; end do
    m%cap = c
    if (allocated(m%key)) deallocate(m%key, m%val, m%used)
    allocate(m%key(0:c-1), m%val(0:c-1), m%used(0:c-1))
    m%used = .false.; m%val = 0
  end subroutine sm_init

  pure integer function sm_hash(s, cap)
    character(len=*), intent(in) :: s
    integer, intent(in) :: cap
    integer :: i
    integer(kind=8) :: h
    h = 5381_8
    do i = 1, len_trim(s)
       h = iand(h * 33_8 + int(iachar(s(i:i)), 8), int(z'7FFFFFFF', 8))
    end do
    sm_hash = int(iand(h, int(cap - 1, 8)))
  end function sm_hash

  integer function sm_get(m, k, dflt)
    type(strmap), intent(in) :: m
    character(len=*), intent(in) :: k
    integer, intent(in) :: dflt
    integer :: h
    sm_get = dflt
    if (m%cap == 0) return
    h = sm_hash(k, m%cap)
    do while (m%used(h))
       if (m%key(h) == k) then
          sm_get = m%val(h); return
       end if
       h = iand(h + 1, m%cap - 1)
    end do
  end function sm_get

  recursive subroutine sm_put(m, k, v)
    type(strmap), intent(inout) :: m
    character(len=*), intent(in) :: k
    integer, intent(in) :: v
    integer :: h, i, oc
    character(len=NL), allocatable :: ok(:)
    integer, allocatable :: ov(:)
    logical, allocatable :: ou(:)
    if (m%cap == 0) call sm_init(m, 16)
    h = sm_hash(k, m%cap)
    do while (m%used(h))
       if (m%key(h) == k) then
          m%val(h) = v; return
       end if
       h = iand(h + 1, m%cap - 1)
    end do
    m%used(h) = .true.; m%key(h) = k; m%val(h) = v
    if (2 * count(m%used) > m%cap) then          ! rehash (rare)
       oc = m%cap
       call move_alloc(m%key, ok); call move_alloc(m%val, ov); call move_alloc(m%used, ou)
       m%cap = 0
       call sm_init(m, oc)
       do i = 0, oc - 1
          if (ou(i)) call sm_put(m, ok(i), ov(i))
       end do
    end if
  end subroutine sm_put

  subroutine grow_int(a, need)
    integer, allocatable, intent(inout) :: a(:)
    integer, intent(in) :: need
    integer, allocatable :: t(:)
    if (.not. allocated(a)) then
       allocate(a(max(need, 64))); return
    end if
    if (size(a) >= need) return
    allocate(t(max(need, 2*size(a))))
    t(1:size(a)) = a
    call move_alloc(t, a)
  end subroutine grow_int

  ! ================================================================== patterns
  integer function pool_add(P, isop, name, l, r)
    type(pattern_pool), intent(inout) :: P
    logical, intent(in) :: isop
    character(len=*), intent(in) :: name
    integer, intent(in) :: l, r
    logical, allocatable :: tb(:)
    character(len=16), allocatable :: tn(:)
    character(len=PL), allocatable :: tr(:)
    integer, allocatable :: ti(:)
    integer :: c
    if (.not. allocated(P%isop)) then
       allocate(P%isop(4096), P%name(4096), P%l(4096), P%r(4096), P%rend(4096))
    else if (P%n == size(P%isop)) then
       c = 2 * size(P%isop)
       allocate(tb(c)); tb(1:P%n) = P%isop; call move_alloc(tb, P%isop)
       allocate(tn(c)); tn(1:P%n) = P%name; call move_alloc(tn, P%name)
       allocate(ti(c)); ti(1:P%n) = P%l; call move_alloc(ti, P%l)
       allocate(ti(c)); ti(1:P%n) = P%r; call move_alloc(ti, P%r)
       allocate(tr(c)); tr(1:P%n) = P%rend; call move_alloc(tr, P%rend)
    end if
    P%n = P%n + 1
    P%isop(P%n) = isop; P%name(P%n) = name; P%l(P%n) = l; P%r(P%n) = r
    if (isop) then
       P%rend(P%n) = '(' // trim(P%rend(l)) // ' ' // trim(name) // ' ' // trim(P%rend(r)) // ')'
    else
       P%rend(P%n) = name
    end if
    pool_add = P%n
  end function pool_add

  !> tokenise a fully parenthesised infix pattern: "(", ")" and maximal non-space runs
  subroutine pat_tokens(s, tok, nt)
    character(len=*), intent(in) :: s
    character(len=16), intent(out) :: tok(:)
    integer, intent(out) :: nt
    integer :: i, j, n
    n = len_trim(s); nt = 0; i = 1
    do while (i <= n)
       if (is_space(s(i:i))) then
          i = i + 1
       else if (s(i:i) == '(' .or. s(i:i) == ')') then
          nt = nt + 1; tok(nt) = s(i:i); i = i + 1
       else
          j = i
          do while (j <= n)
             if (is_space(s(j:j)) .or. s(j:j) == '(' .or. s(j:j) == ')') exit
             j = j + 1
          end do
          nt = nt + 1; tok(nt) = s(i:j-1); i = j
       end if
    end do
  end subroutine pat_tokens

  recursive integer function pat_parse_rec(P, tok, nt, pos, ok) result(id)
    type(pattern_pool), intent(inout) :: P
    character(len=16), intent(in) :: tok(:)
    integer, intent(in) :: nt
    integer, intent(inout) :: pos
    logical, intent(inout) :: ok
    integer :: l, r
    character(len=16) :: op
    id = 0
    if (pos > nt) then
       ok = .false.; return
    end if
    if (tok(pos) == '(') then
       pos = pos + 1
       l = pat_parse_rec(P, tok, nt, pos, ok); if (.not. ok) return
       if (pos > nt) then; ok = .false.; return; end if
       op = tok(pos); pos = pos + 1
       r = pat_parse_rec(P, tok, nt, pos, ok); if (.not. ok) return
       if (pos > nt) then; ok = .false.; return; end if
       if (tok(pos) /= ')') then; ok = .false.; return; end if
       pos = pos + 1
       id = pool_add(P, .true., op, l, r)
    else
       id = pool_add(P, .false., tok(pos), 0, 0)
       pos = pos + 1
    end if
  end function pat_parse_rec

  integer function pat_parse(P, s, ok)
    type(pattern_pool), intent(inout) :: P
    character(len=*), intent(in) :: s
    logical, intent(out) :: ok
    character(len=16) :: tok(128)
    integer :: nt, pos
    call pat_tokens(s, tok, nt)
    ok = .true.; pos = 1
    pat_parse = pat_parse_rec(P, tok, nt, pos, ok)
    if (pos /= nt + 1) ok = .false.
  end function pat_parse

  !> load relations_trs.rules:  name | kind | lhs | rhs | source
  subroutine load_rules(path, P, rules, nrules, ierr)
    character(len=*), intent(in) :: path
    type(pattern_pool), intent(inout) :: P
    type(rule_t), allocatable, intent(out) :: rules(:)
    integer, intent(out) :: nrules, ierr
    integer :: u, ios, k, nf, cap, q
    character(len=LN) :: line
    character(len=256) :: f(5)
    integer :: bar(4)
    type(rule_t), allocatable :: t(:)
    logical :: ok
    nrules = 0; ierr = 0; cap = 2048
    allocate(rules(cap))
    open(newunit=u, file=trim(path), status='old', action='read', iostat=ios)
    if (ios /= 0) then
       ierr = 1; return
    end if
    do
       read(u, '(A)', iostat=ios) line
       if (ios /= 0) exit
       line = adjustl(line)
       if (len_trim(line) == 0) cycle
       if (line(1:1) == '#') cycle
       if (line(1:9) == 'TRS_RULES') cycle
       nf = 0
       do k = 1, len_trim(line)
          if (line(k:k) == '|' .and. nf < 4) then
             nf = nf + 1; bar(nf) = k
          end if
       end do
       if (nf /= 4) then
          write(*,'(A)') 'TRS WARNING: malformed rule line skipped: ' // trim(line)
          cycle
       end if
       f(1) = adjustl(line(1:bar(1)-1))
       f(2) = adjustl(line(bar(1)+1:bar(2)-1))
       f(3) = adjustl(line(bar(2)+1:bar(3)-1))
       f(4) = adjustl(line(bar(3)+1:bar(4)-1))
       f(5) = adjustl(line(bar(4)+1:))
       if (nrules == cap) then
          cap = 2 * cap
          allocate(t(cap)); t(1:nrules) = rules(1:nrules); call move_alloc(t, rules)
       end if
       nrules = nrules + 1
       rules(nrules)%name = f(1)
       rules(nrules)%lhs = pat_parse(P, f(3), ok)
       if (.not. ok) then
          write(*,'(A)') 'TRS WARNING: bad lhs pattern, rule skipped: ' // trim(f(1))
          nrules = nrules - 1; cycle
       end if
       rules(nrules)%rhs = f(4)
       rules(nrules)%source = f(5)
       if (trim(f(4)) == '0') then
          rules(nrules)%rhs_kind = 0
       else
          rules(nrules)%rhs_kind = 1
          if (f(4)(1:1) == '(') then
             q = pat_parse(P, f(4), ok)
             if (ok .and. P%isop(q)) then
                if (is_selector(P%name(q)) .and. .not. P%isop(P%l(q)) .and. &
                    .not. P%isop(P%r(q))) then
                   rules(nrules)%rhs_kind = 2
                   rules(nrules)%rop = P%name(q)
                   rules(nrules)%rl = P%name(P%l(q))
                   rules(nrules)%rr = P%name(P%r(q))
                end if
             end if
          end if
       end if
    end do
    close(u)
  end subroutine load_rules

  ! ================================================================== CTR parsing
  !> resolve an operand name: reaching definition, else (new) leaf
  integer function resolve_name(G, cur, leafid, nm)
    type(prog_t), intent(inout) :: G
    type(strmap), intent(inout) :: cur, leafid
    character(len=*), intent(in) :: nm
    character(len=NL), allocatable :: t(:)
    integer :: v
    v = sm_get(cur, nm, 0)
    if (v /= 0) then
       resolve_name = v; return
    end if
    v = sm_get(leafid, nm, 0)
    if (v /= 0) then
       resolve_name = v; return
    end if
    if (G%nleaves == size(G%leaves)) then
       allocate(t(2 * size(G%leaves))); t(1:G%nleaves) = G%leaves(1:G%nleaves)
       call move_alloc(t, G%leaves)
    end if
    G%nleaves = G%nleaves + 1
    G%leaves(G%nleaves) = nm
    call sm_put(leafid, nm, -G%nleaves)
    resolve_name = -G%nleaves
  end function resolve_name

  subroutine add_ref(G, li, v)
    type(prog_t), intent(inout) :: G
    integer, intent(in) :: li, v
    G%nref = G%nref + 1
    call grow_int(G%refv, G%nref)
    G%refv(G%nref) = v
    G%ref_cnt(li) = G%ref_cnt(li) + 1
  end subroutine add_ref

  subroutine add_edge(G, from, to)
    type(prog_t), intent(inout) :: G
    integer, intent(in) :: from, to
    if (from <= 0) return
    G%nedge = G%nedge + 1
    call grow_int(G%enext, G%nedge); call grow_int(G%eto, G%nedge)
    G%eto(G%nedge) = to
    G%enext(G%nedge) = G%ehead(from)
    G%ehead(from) = G%nedge
  end subroutine add_edge

  !> parse "exec run LHS = A rest"; returns .false. if the line is not of that form
  logical function split_exec_run(s, lhs, a, rest)
    character(len=*), intent(in) :: s
    character(len=*), intent(out) :: lhs, a, rest
    character(len=NL) :: tk(2)
    integer :: nt, i, j, n
    split_exec_run = .false.
    lhs = ''; a = ''; rest = ''
    call split_ws(s, tk, nt)
    if (nt < 2) return
    if (upper(trim(tk(1))) /= 'EXEC' .or. upper(trim(tk(2))) /= 'RUN') return
    n = len_trim(s)
    ! skip "exec" ws "run" ws
    i = 1
    do while (i <= n .and. .not. is_space(s(i:i))); i = i + 1; end do
    do while (i <= n .and. is_space(s(i:i))); i = i + 1; end do
    do while (i <= n .and. .not. is_space(s(i:i))); i = i + 1; end do
    if (i > n) return
    do while (i <= n .and. is_space(s(i:i))); i = i + 1; end do
    j = i
    do while (j <= n)
       if (is_space(s(j:j)) .or. s(j:j) == '=') exit
       j = j + 1
    end do
    if (j == i) return
    lhs = s(i:j-1)
    i = j
    do while (i <= n .and. is_space(s(i:i))); i = i + 1; end do
    if (i > n) return
    if (s(i:i) /= '=') return
    i = i + 1
    do while (i <= n .and. is_space(s(i:i))); i = i + 1; end do
    if (i > n) return
    j = i
    do while (j <= n .and. .not. is_space(s(j:j))); j = j + 1; end do
    a = s(i:j-1)
    if (j <= n) rest = adjustl(s(j:n))
    split_exec_run = .true.
  end function split_exec_run

  subroutine parse_ctr(path, G, ierr)
    character(len=*), intent(in) :: path
    type(prog_t), intent(inout) :: G
    integer, intent(out) :: ierr
    integer :: u, ios, n, li, k, nt, zone, v, nid, i, j, m
    character(len=LN) :: s, rest
    character(len=NL) :: lhs, a, b, tk(64), w1, nm
    character(len=16) :: op
    type(strmap) :: cur, leafid, lastdef, zoneset
    logical :: edge_like, enabled
    ierr = 0; enabled = .true.
    open(newunit=u, file=trim(path), status='old', action='read', iostat=ios)
    if (ios /= 0) then
       ierr = 1; return
    end if
    n = 0
    do
       read(u, '(A)', iostat=ios) s
       if (ios /= 0) exit
       n = n + 1
    end do
    rewind(u)
    G%nlines = n
    allocate(G%lines(n), G%line_node(n), G%has_refs(n), G%ref_off(n), G%ref_cnt(n))
    do li = 1, n
       read(u, '(A)') G%lines(li)
    end do
    close(u)
    G%line_node = 0; G%has_refs = .false.; G%ref_cnt = 0; G%ref_off = 0
    allocate(G%nodes(max(n, 1)), G%leaves(max(2*n, 16)))
    call sm_init(cur, n); call sm_init(leafid, n); call sm_init(G%memdbs, 16)
    call sm_init(zoneset, 16)
    zone = 0
    do li = 1, n
       s = adjustl(G%lines(li))
       call split_ws(s, tk, nt)
       if (nt >= 4) then
          if (upper(trim(tk(1))) == 'START' .and. upper(trim(tk(2))) == 'CONNECT' .and. &
              upper(trim(tk(3))) == 'ZONE') then
             read(tk(4), *, iostat=ios) k
             if (ios == 0) then
                zone = k
                if (sm_get(zoneset, itoa(k), 0) == 0) then
                   call sm_put(zoneset, itoa(k), 1); G%nzones = G%nzones + 1
                end if
                cycle
             end if
          end if
       end if
       if (nt >= 3) then
          if (upper(trim(tk(1))) == 'END' .and. upper(trim(tk(2))) == 'CONNECT' .and. &
              upper(tk(3)(1:4)) == 'ZONE') then
             zone = 0; cycle
          end if
       end if
       if (nt >= 3) then
          if (upper(trim(tk(1))) == 'DECL' .and. upper(trim(tk(2))) == 'MEMORY') then
             nm = tk(3)
             k = index(nm, '=')
             if (k > 0) nm = nm(1:k-1)
             if (len_trim(nm) > 0 .and. (k > 0 .or. nt >= 4)) then
                call sm_put(G%memdbs, trim(nm), 1); cycle
             end if
          end if
       end if
       if (len_trim(s) > 0) then
          if (s(1:1) == '#') cycle
       end if
       if (nt >= 3) then
          if (trim(tk(1)) == 'var' .and. trim(tk(2)) == 'trs_enable') enabled = (trim(tk(3)) /= '0')
       end if
       G%ref_off(li) = G%nref
       G%has_refs(li) = .true.
       if (.not. split_exec_run(s, lhs, a, rest)) then
          ! other line: layer-name tokens are uses of their reaching definitions
          m = len_trim(s); i = 1
          do while (i <= m)
             if (is_idc(s(i:i))) then
                j = i
                do while (j + 1 <= m)
                   if (.not. is_idc(s(j+1:j+1))) exit
                   j = j + 1
                end do
                if (j + 2 <= m) then
                   if (s(j+1:j+1) == ':' .and. (is_idc(s(j+2:j+2)) .or. s(j+2:j+2) == '.')) then
                      k = j + 2
                      do while (k + 1 <= m)
                         if (.not. (is_idc(s(k+1:k+1)) .or. s(k+1:k+1) == '.')) exit
                         k = k + 1
                      end do
                      v = sm_get(cur, s(i:k), 0)
                      if (v /= 0) call add_ref(G, li, v)
                      i = k + 1; cycle
                   end if
                end if
                i = j + 1
             else
                i = i + 1
             end if
          end do
          cycle
       end if
       op = 'OPAQUE'; b = ''
       k = scan(rest, '+@*%^~!')
       if (k > 0) then
          select case (rest(k:k))
          case ('*'); op = '*'
          case ('+'); op = '+'
          case ('@', '!'); op = 'NOT'
          case ('^'); op = '^'
          case default; op = 'OPAQUE'
          end select
          call split_ws(rest(k+1:), tk, nt)
          if (nt >= 1) b = tk(1)
       else
          call split_ws(rest, tk, nt)
          if (nt >= 2) then
             w1 = upper(tk(1))
             edge_like = .false.
             do i = 1, min(nt, 4)
                if (upper(trim(tk(i))) == 'EDGE' .or. upper(trim(tk(i))) == 'COINCIDENT') &
                     edge_like = .true.
             end do
             if (edge_like) then
                op = 'OPAQUE'; b = tk(nt)
             else if (trim(w1) == 'NOT' .and. nt >= 3 .and. in_sel_base(upper(trim(tk(2))))) then
                op = 'NOT_' // upper(trim(tk(2))); b = tk(3)
             else if (trim(w1) == 'AND2') then
                op = '*'; b = tk(2)
             else if (trim(w1) == 'OR2') then
                op = '+'; b = tk(2)
             else if (trim(w1) == 'NOT') then
                op = 'NOT'; b = tk(2)
             else if (trim(w1) == 'XOR') then
                op = '^'; b = tk(2)
             else if (is_selector(trim(w1))) then
                op = trim(w1); b = tk(2)
             else
                op = 'OPAQUE'; b = tk(2)
             end if
          end if
       end if
       G%nnodes = G%nnodes + 1
       nid = G%nnodes
       G%nodes(nid)%line = li
       G%nodes(nid)%lhs = lhs
       G%nodes(nid)%zone = zone
       G%nodes(nid)%frozen = .not. enabled
       G%nodes(nid)%nargs = 1
       G%nodes(nid)%args(1) = resolve_name(G, cur, leafid, trim(a))
       if (len_trim(b) > 0 .and. trim(b) /= 'nothing') then
          G%nodes(nid)%nargs = 2
          G%nodes(nid)%args(2) = resolve_name(G, cur, leafid, trim(b))
       end if
       if (trim(op) /= 'OPAQUE' .and. G%nodes(nid)%nargs /= 2) op = 'OPAQUE'
       G%nodes(nid)%op = op
       G%line_node(li) = nid
       do k = 1, G%nodes(nid)%nargs
          call add_ref(G, li, G%nodes(nid)%args(k))
       end do
       call sm_put(cur, trim(lhs), nid)
    end do
    ! next redefinition of each node's name, and first definition of each leaf name
    call sm_init(lastdef, n)
    do nid = G%nnodes, 1, -1
       G%nodes(nid)%next_redef = sm_get(lastdef, trim(G%nodes(nid)%lhs), huge(1))
       call sm_put(lastdef, trim(G%nodes(nid)%lhs), G%nodes(nid)%line)
    end do
    allocate(G%leaf_first_def(max(G%nleaves, 1)))
    do k = 1, G%nleaves
       G%leaf_first_def(k) = sm_get(lastdef, trim(G%leaves(k)), huge(1))
    end do
    ! users graph
    allocate(G%ehead(max(G%nnodes, 1))); G%ehead = 0
    do nid = 1, G%nnodes
       do k = G%nodes(nid)%nargs, 1, -1
          call add_edge(G, G%nodes(nid)%args(k), nid)
       end do
    end do
  end subroutine parse_ctr

  ! ================================================================== rewriting
  integer function resolvev(G, v0)
    type(prog_t), intent(in) :: G
    integer, intent(in) :: v0
    integer :: v
    v = v0
    do while (v > 0)
       if (G%nodes(v)%state /= ST_ALIAS) exit
       v = G%nodes(v)%target
    end do
    resolvev = v
  end function resolvev

  logical function iszero(G, v)
    type(prog_t), intent(in) :: G
    integer, intent(in) :: v
    iszero = .false.
    if (v > 0) iszero = (G%nodes(v)%state == ST_ZERO)
  end function iszero

  integer function env_get(ek, ev, ne, key)
    character(len=PL), intent(in) :: ek(:)
    integer, intent(in) :: ev(:), ne
    character(len=*), intent(in) :: key
    integer :: i
    env_get = 0
    do i = 1, ne
       if (ek(i) == key) then
          env_get = ev(i); return
       end if
    end do
  end function env_get

  recursive logical function pmatch(G, PP, ip, v0, ek, ev, ne) result(ok)
    type(prog_t), intent(in) :: G
    type(pattern_pool), intent(in) :: PP
    integer, intent(in) :: ip, v0
    character(len=PL), intent(inout) :: ek(:)
    integer, intent(inout) :: ev(:), ne
    integer :: v, i
    ok = .false.
    v = resolvev(G, v0)
    if (.not. PP%isop(ip)) then
       do i = 1, ne
          if (ek(i) == PP%rend(ip)) then
             ok = (ev(i) == v); return
          end if
       end do
       ne = ne + 1; ek(ne) = PP%rend(ip); ev(ne) = v
       ok = .true.; return
    end if
    if (v <= 0) return
    associate (nd => G%nodes(v))
      if (nd%state /= ST_KEEP .or. nd%zone /= 0 .or. nd%op /= PP%name(ip)) return
      if (.not. pmatch(G, PP, PP%l(ip), nd%args(1), ek, ev, ne)) return
      if (.not. pmatch(G, PP, PP%r(ip), nd%args(2), ek, ev, ne)) return
    end associate
    ne = ne + 1; ek(ne) = PP%rend(ip); ev(ne) = v
    ok = .true.
  end function pmatch

  !> can value v be referred to by its name at line li (no intervening redefinition)?
  logical function nameable(G, v, li)
    type(prog_t), intent(in) :: G
    integer, intent(in) :: v, li
    if (v < 0) then
       nameable = G%leaf_first_def(-v) >= li
    else
       nameable = G%nodes(v)%line < li .and. G%nodes(v)%next_redef >= li
    end if
  end function nameable

  function vname(G, v) result(s)
    type(prog_t), intent(in) :: G
    integer, intent(in) :: v
    character(len=:), allocatable :: s
    if (v < 0) then
       s = trim(G%leaves(-v))
    else
       s = trim(G%nodes(v)%lhs)
    end if
  end function vname

  logical function consumed_in_zone(G, id)
    type(prog_t), intent(in) :: G
    integer, intent(in) :: id
    integer :: k, j
    consumed_in_zone = .false.
    do k = 1, G%nnodes
       if (G%nodes(k)%zone <= 0) cycle
       do j = 1, G%nodes(k)%nargs
          if (G%nodes(k)%args(j) == id .or. resolvev(G, G%nodes(k)%args(j)) == id) then
             consumed_in_zone = .true.; return
          end if
       end do
    end do
  end function consumed_in_zone

  !> does value id reach a selector operand through any chain of later ops?
  logical function feeds_selector(G, id, seen, stack)
    type(prog_t), intent(in) :: G
    integer, intent(in) :: id
    logical, intent(inout) :: seen(:)
    integer, intent(inout) :: stack(:)
    integer :: sp, v, e, m, nseen
    integer, allocatable :: touched(:)
    feeds_selector = .false.
    allocate(touched(G%nnodes)); nseen = 0
    sp = 1; stack(1) = id
    outer: do while (sp > 0)
       v = stack(sp); sp = sp - 1
       if (seen(v)) cycle
       seen(v) = .true.; nseen = nseen + 1; touched(nseen) = v
       e = G%ehead(v)
       do while (e > 0)
          m = G%eto(e)
          if (is_selector(G%nodes(m)%op)) then
             feeds_selector = .true.; exit outer
          end if
          if (.not. seen(m)) then
             sp = sp + 1; stack(sp) = m
          end if
          e = G%enext(e)
       end do
    end do outer
    seen(touched(1:nseen)) = .false.
  end function feeds_selector

  logical function set_alias(G, nid, t, why, box_equal, seen, stack)
    type(prog_t), intent(inout) :: G
    integer, intent(in) :: nid, t
    character(len=*), intent(in) :: why
    logical, intent(in) :: box_equal
    logical, intent(inout) :: seen(:)
    integer, intent(inout) :: stack(:)
    set_alias = .false.
    if (.not. nameable(G, t, G%nodes(nid)%line)) return
    if (consumed_in_zone(G, nid)) return
    if (.not. box_equal) then
       if (feeds_selector(G, nid, seen, stack)) return
    end if
    G%nodes(nid)%state = ST_ALIAS
    G%nodes(nid)%target = t
    G%nodes(nid)%why = why
    call add_edge(G, t, nid)
    set_alias = .true.
  end function set_alias

  logical function fold(G, nid, seen, stack)
    type(prog_t), intent(inout) :: G
    integer, intent(in) :: nid
    logical, intent(inout) :: seen(:)
    integer, intent(inout) :: stack(:)
    integer :: a, b
    logical :: za, zb
    character(len=16) :: op
    fold = .false.
    a = resolvev(G, G%nodes(nid)%args(1)); b = resolvev(G, G%nodes(nid)%args(2))
    za = iszero(G, a); zb = iszero(G, b)
    if (.not. (za .or. zb)) return
    op = G%nodes(nid)%op
    if (trim(op) == '*') then
       call set_zero(G, nid, 'X * 0 = 0'); fold = .true.
    else if (trim(op) == '+' .or. trim(op) == '^') then
       if (za) then
          fold = set_alias(G, nid, b, '0 ' // trim(op) // ' X = X', .false., seen, stack)
       else
          fold = set_alias(G, nid, a, 'X ' // trim(op) // ' 0 = X', .false., seen, stack)
       end if
    else if (trim(op) == 'NOT') then
       if (za) then
          call set_zero(G, nid, '0 NOT X = 0'); fold = .true.; return
       end if
       fold = set_alias(G, nid, a, 'X NOT 0 = X', .false., seen, stack)
    else if (is_selector(op)) then
       if (za) then
          call set_zero(G, nid, 'selector on empty A = 0'); fold = .true.; return
       end if
       if (any(KEEP_IF_B_EMPTY == op)) then
          fold = set_alias(G, nid, a, 'A ' // trim(op) // ' 0 = A (engine empty-B branch)', &
                           .false., seen, stack)
          return
       end if
       call set_zero(G, nid, 'A ' // trim(op) // ' 0 = 0 (engine empty-B branch)')
       fold = .true.
    end if
  end function fold

  subroutine set_zero(G, nid, why)
    type(prog_t), intent(inout) :: G
    integer, intent(in) :: nid
    character(len=*), intent(in) :: why
    G%nodes(nid)%state = ST_ZERO
    G%nodes(nid)%why = why
  end subroutine set_zero

  logical function apply_rule(G, P, r, nid, seen, stack)
    type(prog_t), intent(inout) :: G
    type(pattern_pool), intent(in) :: P
    type(rule_t), intent(in) :: r
    integer, intent(in) :: nid
    logical, intent(inout) :: seen(:)
    integer, intent(inout) :: stack(:)
    character(len=PL) :: ek(32)
    integer :: ev(32), ne, x, y, t
    character(len=WL) :: why
    apply_rule = .false.
    ne = 0
    if (.not. pmatch(G, P, r%lhs, nid, ek, ev, ne)) return
    why = trim(r%name) // ' [' // trim(r%source) // ']'
    select case (r%rhs_kind)
    case (0)
       call set_zero(G, nid, trim(why)); apply_rule = .true.
    case default
       t = env_get(ek, ev, ne, trim(r%rhs))
       if (t /= 0) then
          apply_rule = set_alias(G, nid, t, trim(why), .false., seen, stack)
          return
       end if
       if (r%rhs_kind /= 2) return
       x = env_get(ek, ev, ne, trim(r%rl)); y = env_get(ek, ev, ne, trim(r%rr))
       if (x == 0 .or. y == 0) return
       if (.not. nameable(G, x, G%nodes(nid)%line)) return
       if (.not. nameable(G, y, G%nodes(nid)%line)) return
       if (consumed_in_zone(G, nid)) return
       ! never emit an in-place op (lhs name = operand name): the engine aliases the buffers
       if (vname(G, x) == trim(G%nodes(nid)%lhs) .or. vname(G, y) == trim(G%nodes(nid)%lhs)) return
       if (feeds_selector(G, nid, seen, stack)) return
       G%nodes(nid)%state = ST_REPLACE
       G%nodes(nid)%newop = r%rop
       G%nodes(nid)%newargs = [x, y]
       G%nodes(nid)%why = why
       apply_rule = .true.
    end select
  end function apply_rule

  !> built-in: sel(sel(A,B),B) = sel(A,B)  (Lean: Trs.Box.nest_eq, a box-list equality)
  logical function sel_idem(G, nid, seen, stack)
    type(prog_t), intent(inout) :: G
    integer, intent(in) :: nid
    logical, intent(inout) :: seen(:)
    integer, intent(inout) :: stack(:)
    integer :: a, b
    sel_idem = .false.
    if (.not. is_selector(G%nodes(nid)%op)) return
    a = resolvev(G, G%nodes(nid)%args(1)); b = resolvev(G, G%nodes(nid)%args(2))
    if (a <= 0) return
    if (G%nodes(a)%state /= ST_KEEP .or. G%nodes(a)%op /= G%nodes(nid)%op) return
    if (G%nodes(a)%nargs < 2) return
    if (resolvev(G, G%nodes(a)%args(2)) /= b) return
    sel_idem = set_alias(G, nid, a, 'sel_idem [Trs.Box.nest_eq]', .true., seen, stack)
  end function sel_idem

  subroutine optimize(G, P, rules, nrules)
    type(prog_t), intent(inout) :: G
    type(pattern_pool), intent(in) :: P
    type(rule_t), intent(in) :: rules(:)
    integer, intent(in) :: nrules
    logical, allocatable :: seen(:)
    integer, allocatable :: stack(:)
    integer :: nid, k, limit, cnt, ios
    character(len=32) :: ev
    logical :: done
    limit = huge(1)
    call get_environment_variable('TRS_MAX_REWRITES', ev, status=ios)
    if (ios == 0) read(ev, *, iostat=ios) limit
    allocate(seen(max(G%nnodes, 1)), stack(max(G%nedge + G%nnodes, 1) * 2 + 16))
    seen = .false.
    cnt = 0
    do nid = 1, G%nnodes
       if (cnt >= limit) exit
       if (G%nodes(nid)%zone > 0 .or. G%nodes(nid)%frozen) cycle
       if (trim(G%nodes(nid)%op) == 'OPAQUE') cycle
       done = fold(G, nid, seen, stack)
       if (.not. done) done = sel_idem(G, nid, seen, stack)
       if (.not. done) then
          do k = 1, nrules
             if (apply_rule(G, P, rules(k), nid, seen, stack)) then
                done = .true.; exit
             end if
          end do
       end if
       if (done) then
          cnt = cnt + 1
          if (cnt == limit) write(*,'(A,I0,A)') 'TRS: last rewrite at line ', &
               G%nodes(nid)%line, ': ' // trim(G%nodes(nid)%why)
       end if
    end do
  end subroutine optimize

  ! ================================================================== emission
  pure function dbof(name) result(s)
    character(len=*), intent(in) :: name
    character(len=:), allocatable :: s
    integer :: k
    k = index(name, ':')
    if (k == 0) then
       s = ''
    else
       s = name(1:k-1)
    end if
  end function dbof

  !> provably-empty lines and orphaned memory temporaries not used by any kept line
  subroutine live_lines(G, dropped)
    type(prog_t), intent(in) :: G
    logical, intent(out) :: dropped(:)
    logical, allocatable :: orig_used(:), used(:)
    integer :: li, k, v, nid
    logical :: changed
    allocate(orig_used(max(G%nnodes, 1)), used(max(G%nnodes, 1)))
    orig_used = .false.; dropped = .false.
    do li = 1, G%nlines
       if (.not. G%has_refs(li)) cycle
       do k = 1, G%ref_cnt(li)
          v = G%refv(G%ref_off(li) + k)
          if (v > 0) orig_used(v) = .true.
       end do
    end do
    do
       used = .false.
       do li = 1, G%nlines
          if (.not. G%has_refs(li)) cycle
          nid = G%line_node(li)
          if (nid > 0) then
             if (dropped(nid)) cycle
             if (G%nodes(nid)%state == ST_ALIAS) then
                if (G%nodes(nid)%target > 0) used(G%nodes(nid)%target) = .true.
                cycle
             else if (G%nodes(nid)%state == ST_REPLACE) then
                do k = 1, 2
                   if (G%nodes(nid)%newargs(k) > 0) used(G%nodes(nid)%newargs(k)) = .true.
                end do
                cycle
             end if
          end if
          do k = 1, G%ref_cnt(li)
             v = G%refv(G%ref_off(li) + k)
             if (v > 0) used(v) = .true.
          end do
       end do
       changed = .false.
       do nid = 1, G%nnodes
          if (dropped(nid) .or. used(nid) .or. G%nodes(nid)%frozen) cycle
          if (sm_get(G%memdbs, dbof(trim(G%nodes(nid)%lhs)), 0) == 0) cycle
          if (G%nodes(nid)%state == ST_ZERO .or. (G%nodes(nid)%state == ST_KEEP .and. &
              orig_used(nid) .and. trim(G%nodes(nid)%op) /= 'OPAQUE')) then
             dropped(nid) = .true.; changed = .true.
          end if
       end do
       if (.not. changed) exit
    end do
  end subroutine live_lines

  subroutine write_ctr(path, G, st, ierr)
    character(len=*), intent(in) :: path
    type(prog_t), intent(in) :: G
    integer, intent(out) :: st(5)     ! removed, copy, replace, kept_empty, orphan
    integer, intent(out) :: ierr
    logical, allocatable :: dropped(:)
    integer :: u, li, nid, ios
    character(len=:), allocatable :: ln
    allocate(dropped(max(G%nnodes, 1)))
    call live_lines(G, dropped)
    st = 0; ierr = 0
    open(newunit=u, file=trim(path), status='replace', action='write', iostat=ios)
    if (ios /= 0) then
       ierr = 1; return
    end if
    do li = 1, G%nlines
       ln = trim(G%lines(li))
       nid = G%line_node(li)
       if (nid == 0) then
          write(u, '(A)') ln; cycle
       end if
       associate (nd => G%nodes(nid))
         if (dropped(nid)) then
            if (nd%state == ST_KEEP) then
               write(u, '(A)') '# TRS: removed (result no longer used): ' // trim(adjustl(ln))
               st(5) = st(5) + 1
            else
               if (nd%state == ST_ZERO) then
                  write(u, '(A)') '# TRS: removed, provably empty by ' // trim(nd%why)
               else
                  write(u, '(A)') '# TRS: removed, redundant by ' // trim(nd%why)
               end if
               write(u, '(A)') '# ' // trim(adjustl(ln))
               st(1) = st(1) + 1
            end if
         else if (nd%state == ST_ZERO) then
            write(u, '(A)') '# TRS: provably empty by ' // trim(nd%why) // '; kept because ' // &
                 trim(nd%lhs) // ' is used later'
            write(u, '(A)') ln
            st(4) = st(4) + 1
         else if (nd%state == ST_ALIAS .and. vname(G, nd%target) == trim(nd%lhs)) then
            ! the name already holds the value: emit nothing (the engine's `X = X COPY nothing`
            ! is not a no-op, it destroys X)
            write(u, '(A)') '# TRS: removed, ' // trim(nd%lhs) // ' already holds this value by ' &
                 // trim(nd%why)
            write(u, '(A)') '# ' // trim(adjustl(ln))
            st(1) = st(1) + 1
         else if (nd%state == ST_ALIAS) then
            write(u, '(A)') '# TRS: ' // trim(nd%why)
            write(u, '(A)') 'exec run ' // trim(nd%lhs) // ' = ' // vname(G, nd%target) // &
                 ' COPY nothing'
            st(2) = st(2) + 1
         else if (nd%state == ST_REPLACE) then
            write(u, '(A)') '# TRS: ' // trim(nd%why)
            write(u, '(A)') 'exec run ' // trim(nd%lhs) // ' = ' // vname(G, nd%newargs(1)) // &
                 ' ' // trim(nd%newop) // ' ' // vname(G, nd%newargs(2))
            st(3) = st(3) + 1
         else
            write(u, '(A)') ln
         end if
       end associate
    end do
    close(u)
  end subroutine write_ctr

  ! ================================================================== public API
  !> Rules file to use for a CTR: `var trs_rules <path>` in the file wins (value `none`/`off`
  !> disables), else the MAGPARSER_TRS_RULES environment variable, else '' (TRS off).
  subroutine TRSFindRulesFile(ctr_path, rules_path)
    character(len=*), intent(in) :: ctr_path
    character(len=*), intent(out) :: rules_path
    integer :: u, ios, nt
    character(len=LN) :: s
    character(len=NL) :: tk(4)
    rules_path = ''
    call get_environment_variable('MAGPARSER_TRS_RULES', rules_path, status=ios)
    if (ios /= 0) rules_path = ''
    open(newunit=u, file=trim(ctr_path), status='old', action='read', iostat=ios)
    if (ios /= 0) return
    do
       read(u, '(A)', iostat=ios) s
       if (ios /= 0) exit
       call split_ws(s, tk, nt)
       if (nt >= 3) then
          if (trim(tk(1)) == 'var' .and. trim(tk(2)) == 'trs_rules') rules_path = tk(3)
       end if
    end do
    close(u)
    if (upper(trim(rules_path)) == 'NONE' .or. upper(trim(rules_path)) == 'OFF' .or. &
        trim(rules_path) == '0') rules_path = ''
  end subroutine TRSFindRulesFile

  !> Optimize CTR file in_path with the rules in rules_path, writing out_path.
  !> status: 0 ok, 1 rules file unreadable, 2 CTR unreadable, 3 output unwritable.
  subroutine TRSOptimizeFile(rules_path, in_path, out_path, verbose, status)
    character(len=*), intent(in) :: rules_path, in_path, out_path
    logical, intent(in) :: verbose
    integer, intent(out) :: status
    type(pattern_pool) :: P
    type(rule_t), allocatable :: rules(:)
    type(prog_t) :: G
    integer :: nrules, ierr, st(5), removed
    logical :: q
    q = .not. verbose
    status = 0
    call load_rules(rules_path, P, rules, nrules, ierr)
    if (ierr /= 0) then
       write(*,'(A)') 'TRS ERROR: cannot read rules file: ' // trim(rules_path)
       status = 1; return
    end if
    call parse_ctr(in_path, G, ierr)
    if (ierr /= 0) then
       write(*,'(A)') 'TRS ERROR: cannot read CTR file: ' // trim(in_path)
       status = 2; return
    end if
    call optimize(G, P, rules, nrules)
    call write_ctr(out_path, G, st, ierr)
    if (ierr /= 0) then
       write(*,'(A)') 'TRS ERROR: cannot write: ' // trim(out_path)
       status = 3; return
    end if
    if (q) return
    removed = st(1) + st(5)
    write(*,'(A,I0)') 'Rules loaded:            ', nrules
    write(*,'(A,I0)') 'Ops before:              ', G%nnodes
    write(*,'(A,I0,A,I0,A,I0,A)') 'Ops removed:             ', removed, '  (rewritten ', &
         st(1), ', orphaned ', st(5), ')'
    write(*,'(A,I0)') 'Ops replaced by COPY:    ', st(2)
    write(*,'(A,I0)') 'Ops replaced by 1 op:    ', st(3)
    write(*,'(A,I0)') 'Provably empty, kept:    ', st(4)
    write(*,'(A,I0)') 'Ops after:               ', G%nnodes - removed
    write(*,'(A,I0,A)') 'Connectivity zones:      ', G%nzones, ' (no rewrites inside)'
  end subroutine TRSOptimizeFile

end module TRSOptimizerModule
