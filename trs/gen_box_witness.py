#!/usr/bin/env python3
"""Emit lean/Trs/BoxWitness.lean: one healed configuration (A, B, cell) per valid point type.

Witnesses are found by search in boxmodel.py; Lean re-checks every one by `decide +kernel`
(Trs/BoxComplete.lean), so this script is untrusted."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import boxmodel as bm

def search_realizable():
    # same search as boxmodel.search_witnesses, restricted to the 41 realizable types
    from itertools import product
    lo, hi = -2, 9
    cands = {c: [] for c in range(8)}
    rng = range(lo, hi)
    for x1, x2 in product(rng, rng):
        if x1 >= x2: continue
        for y1, y2 in product(rng, rng):
            if y1 >= y2: continue
            b = (x1, y1, x2, y2); c = bm.cls(bm.A_BOX, b)
            if c != bm.DISJ: cands[c].append(b)
    def dfs(classes, chosen):
        if not classes: return list(chosen)
        for b in cands[classes[0]]:
            if all(bm.idisjoint(b, o) for o in chosen):
                r = dfs(classes[1:], chosen + [b])
                if r is not None: return r
        return None
    W = {}
    for T in bm.R_HEALED:
        cl = sorted([c for c in range(8) if (T >> c) & 1], key=lambda c: len(cands[c]))
        w = dfs(cl, [])
        assert w is not None and bm.tmask(bm.A_BOX, w) == T, T
        W[T] = w
    return W

def lbox(b): return '⟨%d, %d, %d, %d⟩' % b
def lty(T): return '⟨' + ', '.join('true' if (T >> c) & 1 else 'false' for c in range(8)) + '⟩'
def lb(x): return 'true' if x else 'false'

def main():
    W = search_realizable()
    rows = []
    for (mA, mB, T) in bm.point_types():
        if not mA:
            A, B, cell = [], ([(0, 0, 1, 1)] if mB else []), (0, 0)
        else:
            A, B = [bm.A_BOX], W[T]
            cell = bm.cell_witness(T, mB, B)
            assert cell is not None
        rows.append('  (⟨%s, %s, %s⟩, ⟨[%s], [%s], (%d, %d)⟩)' % (
            lb(mA), lb(mB), lty(T), ', '.join(map(lbox, A)), ', '.join(map(lbox, B)), *cell))
    out = ['/- Generated by trs/gen_box_witness.py — do not edit.',
           '   One healed configuration per valid point type; checked in Trs/BoxComplete.lean. -/',
           'import Trs.BoxTopo', 'namespace Trs.Box', '',
           'structure Wit where', '  A : List Box', '  B : List Box', '  c : Cell', '',
           'def witTable : List (PT × Wit) := [', ',\n'.join(rows), ']', '', 'end Trs.Box', '']
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'lean', 'Trs', 'BoxWitness.lean')
    open(path, 'w').write('\n'.join(out))
    print('witnesses:', len(rows), '->', os.path.normpath(path))

if __name__ == '__main__':
    main()
