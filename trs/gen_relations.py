#!/usr/bin/env python3
"""Independent generator for the TRS relation lists, and writer of RELATIONS.md.

Two implementations exist on purpose:
  * Lean  (lean/Trs/*.lean)   : definitions + proofs; lists printed by lean/Export.lean
  * Python (this file)        : truth-table masks / boxmodel.py point types
`--check DIR` compares this file's lists with Lean's export in DIR, line by line.

Enumeration order and rendering mirror Trs.Bool.levels / Trs.Box.mlevels exactly.
"""
import argparse, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import boxmodel as bm

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
NAMES = 'ABCDEF'
OPS = [('*', lambda x, y, F: x & y), ('+', lambda x, y, F: x | y),
       ('NOT', lambda x, y, F: x & ~y & F), ('^', lambda x, y, F: x ^ y)]

def levels(atoms, k, F):
    """atoms: list of (render, mask). Returns list of levels of (render, mask)."""
    lv = [list(atoms)]
    for _ in range(k):
        s = len(lv); nxt = []
        for i in range(s):
            for xr, xm in lv[i]:
                for yr, ym in lv[s - 1 - i]:
                    for sym, f in OPS:
                        nxt.append((f'({xr} {sym} {yr})', f(xm, ym, F)))
        lv.append(nxt)
    return lv

def relation_lists(atoms, k, F):
    lv = levels(atoms, k, F)
    terms = [t for l in lv for t in l]
    zero = [r for r, m in terms if m == 0]
    atom = []
    for r, m in (t for l in lv[1:] for t in l):
        for ar, am in atoms:
            if m == am:
                atom.append(f'{r} == {ar}'); break
    return terms, zero, atom

# ---------------- Boolean (2^n truth tables) ----------------
def bool_lists(n, k=3):
    N = 1 << n; F = (1 << N) - 1
    atoms = [(NAMES[i], sum(1 << p for p in range(N) if (p >> i) & 1)) for i in range(n)]
    return relation_lists(atoms, k, F)

# ---------------- 9E-DIM / topological selectors (71 point types) ----------------
BASES = ['INTERACT', 'INSIDE', 'OUTSIDE', 'TOUCH', 'CUT', 'DISJOINT', 'MEET', 'EQUAL',
         'CONTAINS', 'COVERS', 'COVEREDBY', 'OVERLAPS']
OPNAMES = BASES + ['NOT_' + b for b in BASES]

def box_atoms():
    pts = bm.point_types()
    def mask(f): return sum(1 << i for i, p in enumerate(pts) if f(p))
    atoms = [('A', mask(lambda p: p[0])), ('B', mask(lambda p: p[1]))]
    for op in OPNAMES:
        atoms.append((f'(A {op} B)', mask(lambda p, op=op: p[0] and bm.SEL[op](p[2]))))
    return atoms, (1 << len(pts)) - 1, pts

def box_lists(k):
    atoms, F, _ = box_atoms()
    return relation_lists(atoms, k, F)

def box_atomeqs():
    atoms, _, _ = box_atoms()
    out = []
    for i in range(len(atoms)):
        for j in range(len(atoms)):
            if i < j and atoms[i][1] == atoms[j][1]:
                out.append(f'{atoms[j][0]} == {atoms[i][0]}')
    return out

# ---------------- RELATIONS.md ----------------
def uses(term, var):
    lhs = term.split(' == ')[0]
    return var in lhs.replace('(', ' ').replace(')', ' ').split()

