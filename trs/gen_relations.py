def write_rules(path):
    """relations_trs.json for trs_dag.jl: rewrite rules taken from the Lean-checked lists."""
    import json
    rules = []
    _, z, a = bool_lists(3)
    small = lambda r: r.split(' == ')[0].count('(') <= 2
    for i, r in enumerate(x for x in z if small(x)):
        rules.append({'name': f'bool_zero_{i}', 'lhs': r, 'rhs': '0', 'kind': 'zero', 'model': 'bool',
                      'source': 'Trs.Bool.zeroTerms 3 3 (zeroTerms_spec)'})
    _, bz, ba = box_lists(1)
    for i, r in enumerate(bz):
        rules.append({'name': f'box_zero_{i}', 'lhs': r, 'rhs': '0', 'kind': 'zero', 'model': 'box',
                      'source': 'Trs.Box.mzeroTerms 1 (mzeroTerms_spec)'})
    for i, r in enumerate(ba):
        l, rhs = r.split(' == ')
        rules.append({'name': f'box_atom_{i}', 'lhs': l, 'rhs': rhs, 'kind': 'atom', 'model': 'box',
                      'source': 'Trs.Box.matomTerms 1 (matomTerms_sound)'})
    for i, r in enumerate(x for x in a if small(x)):
        l, rhs = r.split(' == ')
        rules.append({'name': f'bool_input_{i}', 'lhs': l, 'rhs': rhs, 'kind': 'atom', 'model': 'bool',
                      'source': 'Trs.Bool.inputTerms 3 3 (inputTerms_sound)'})
    doc = {
        'generator': 'trs/gen_relations.py',
        'semantics': 'RELATIONS.md#semantics; box rules assume healed operands (always true in '
                     'CalculateTopologicalSelect, which preprocesses both operands)',
        'ops': {'*': '* or AND2', '+': '+ or OR2', 'NOT': 'NOT, @, !', '^': 'XOR or ^'},
        'rules': rules,
    }
    with open(path, 'w') as f:
        json.dump(doc, f, indent=1)
    print('wrote', path, len(rules), 'rules')
    write_rules_txt(os.path.splitext(path)[0] + '.rules', rules)

def write_rules_txt(path, rules):
    """relations_trs.rules: the same rules in a line format read by MAGPARSER at compile time
    (src/trs_optimizer.f90).  One rule per line, fields separated by ' | '."""
    L = ['# relations_trs.rules -- CTR term-rewrite rules for MAGPARSER (src/trs_optimizer.f90)',
         '# Generated by trs/gen_relations.py from the Lean-checked lists; do not edit by hand.',
         '# Enable in a CTR with:   var trs_rules /path/to/relations_trs.rules',
         '#   or for every run with: export MAGPARSER_TRS_RULES=/path/to/relations_trs.rules',
         '# Patterns are fully parenthesised infix over pattern variables A, B, C and the CTR',
         '# operators *, +, NOT, ^ and the 24 selectors (NOT_x written with underscore).',
         '# rhs is 0 (empty layer), a pattern variable, a sub-pattern of lhs, or (X SEL Y).',
         '# format:  name | kind | lhs | rhs | source',
         f'TRS_RULES 1 {len(rules)}']
    for r in rules:
        L.append(' | '.join([r['name'], r['kind'], r['lhs'], r['rhs'], r['source']]))
    open(path, 'w').write('\n'.join(L) + '\n')
    print('wrote', path, len(rules), 'rules')

def check(d):
    ok = True
    def cmp(name, mine):
        nonlocal ok
        theirs = open(os.path.join(d, name)).read().splitlines()
        same = theirs == mine
        ok &= same
        print(f'{name:22s} python={len(mine):6d} lean={len(theirs):6d} {"OK" if same else "MISMATCH"}')
    for n in (2, 3, 4):
        _, z, a = bool_lists(n)
        cmp(f'bool_zero_n{n}.txt', z)
        cmp(f'bool_input_n{n}.txt', a)
    _, z, a = box_lists(1)
    cmp('box_zero_s1.txt', z)
    cmp('box_atom_s1.txt', a)
    cmp('box_atomeq.txt', box_atomeqs())
    return ok

if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', metavar='DIR', help='compare with Lean export in DIR')
    ap.add_argument('--md', default=os.path.join(ROOT, 'RELATIONS.md'))
    ap.add_argument('--no-md', action='store_true')
    a = ap.parse_args()
    if a.check:
        sys.exit(0 if check(a.check) else 1)
    if not a.no_md:
        write_md(a.md)
        write_rules(os.path.join(ROOT, 'relations_trs.json'))
